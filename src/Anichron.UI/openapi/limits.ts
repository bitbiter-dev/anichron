import { readFileSync, writeFileSync } from 'node:fs';

interface Schema {
  maxItems?: number;
  maximum?: number;
}

interface ApiDocument {
  components: { schemas: Record<string, { properties?: Record<string, Schema> } | undefined> };
  paths: Record<
    string,
    Record<string, { parameters?: { name: string; schema: Schema }[] } | undefined> | undefined
  >;
}

const source = '../../docs/openapi/v1.json';
const target = 'src/api/generated/limits.ts';

const document = JSON.parse(readFileSync(source, 'utf8')) as ApiDocument;

function published(value: number | undefined, what: string) {
  if (value === undefined) throw new Error(`${source} publishes no ${what}.`);
  return value;
}

const limit = (path: string, name: string) =>
  document.paths[path]?.get?.parameters?.find((parameter) => parameter.name === name)?.schema;

const limits = {
  mostPurgedAssets: published(
    document.components.schemas.PurgeRequest?.properties?.assetIds?.maxItems,
    'maxItems for PurgeRequest.assetIds',
  ),
  mostRecentDays: published(
    limit('/api/v1/flashbacks/days', 'limit')?.maximum,
    'maximum for the limit of GET /api/v1/flashbacks/days',
  ),
};

const text = [
  `// Generated by \`pnpm openapi\` from docs/openapi/v1.json. Do not edit.`,
  ...Object.entries(limits).map(([name, value]) => `export const ${name} = ${String(value)};`),
  '',
].join('\n');

if (!process.argv.includes('--check')) writeFileSync(target, text);
else if (readFileSync(target, 'utf8') !== text) {
  console.error(`${target} is stale: run pnpm openapi.`);
  process.exit(1);
}
